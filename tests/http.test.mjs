import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { Tasks } from '../core/tasks.mjs';
import { Storage } from '../core/storage.mjs';
import { startService, clientKey } from '../core/service.mjs';
test('HTTP monitor and client boundaries reject cross-origin requests and keep reporter tokens scoped', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ag-http-test-')); const storage = new Storage(root);
  const settings = { port: 0, backend: 'native', cli: {}, allowedWorkspaces: [root], target: { model: 'gemini-4-hydrogen-high', effort: 'high', approved: true } };
  const manager = new Tasks({ storage, settings, native: { health: async () => ({ ok: true }), start: async () => 'native-test-session' } });
  const running = await startService({ tasks: manager, settings, authenticationSecret: 'offline-test', stateDirectory: root });
  const base = `http://127.0.0.1:${running.server.address().port}`;
  const headers = role => ({ authorization: 'Bearer ' + clientKey(role, 'offline-test'), 'content-type': 'application/json' });
  t.after(async () => { for (const timer of manager.timers.values()) clearTimeout(timer); await running.close(); storage.close(); fs.rmSync(root, { recursive: true, force: true }); });
  assert.equal((await fetch(base + '/api/tasks')).status, 401);
  assert.equal((await fetch(base + '/api/tasks', { headers: { ...headers('codex'), origin: 'https://evil.example' } })).status, 403);
  const invalidHost = await new Promise((resolve, reject) => { const request = http.get(base + '/api/tasks', { headers: { ...headers('codex'), host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }); request.on('error', reject); });
  assert.equal(invalidHost, 403);
  const created = await fetch(base + '/api/tasks', { method: 'POST', headers: headers('codex'), body: JSON.stringify({ task: '<img src=x onerror=alert(1)>', conversation_id: 'source-chat', workspace: root }) });
  assert.equal(created.status, 202); const task = await created.json(); assert(!('report_token' in task));
  assert.equal((await fetch(base + '/api/tasks/' + task.id, { headers: headers('dsh') })).status, 400);
  const list = await (await fetch(base + '/api/tasks', { headers: headers('dsh') })).json(); assert.equal(list.tasks.length, 0);
  assert.equal((await fetch(base + '/api/tasks', { headers: headers('reporter') })).status, 403);
  const page = await fetch(base); const cookie = page.headers.get('set-cookie').split(';')[0];
  assert(page.headers.get('content-security-policy').includes("frame-ancestors 'none'"));
  assert.equal((await fetch(base + '/api/tasks', { headers: { cookie } })).status, 200);
  assert.equal((await fetch(base + '/api/tasks', { method: 'POST', headers: { cookie }, body: '{}' })).status, 405);
});
